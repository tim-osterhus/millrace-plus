def lstat(kind: int, **changes: int) -> SimpleNamespace:
    facts = {
        "st_mode": kind | 0o755,
        "st_uid": 1000,
        "st_gid": 1000,
        "st_size": 4096,
        "st_mtime_ns": 1_700_000_000_000_000_000,
        "st_ino": 7,
        "st_dev": 3,
    }
    facts.update(changes)
    return SimpleNamespace(**facts)


