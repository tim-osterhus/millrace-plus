def layer(
    status: str, previous: dict[str, object] | None, **changes: object
) -> dict[str, object]:
    record: dict[str, object] = {
        "format": cc.PRODUCTS,
        "input_id": None,
        "materialization_id": None,
        "command_id": "unit",
        "path_policy_ref": POLICY_REF,
        "before_ref": BEFORE,
        "after_ref": None if status == "reserved" else AFTER,
        "owned_paths": [] if status == "reserved" else list(OWNED),
        "completion_ref": ACCEPTANCE if status in {"accepted", "restored"} else None,
        "previous_ref": previous,
        "status": status,
    }
    record.update(changes)
    return record


def chain(subject: str, value: str) -> list[tuple[bytes, dict[str, object]]]:
    links: list[tuple[bytes, dict[str, object]]] = []
    previous = None
    for status in ("reserved", "observed", "accepted", "restored"):
        raw = cc.encode(layer(status, previous, **{subject: value}))
        links.append((raw, cc.make_ref(f"products/{status}.json", raw)))
        previous = links[-1][1]
    return links


@pytest.mark.parametrize(
    "subject,value",
    [("input_id", "a" * 64), ("materialization_id", "materialization-1")],
)
def test_product_layer_lifecycle_for_lq_inputs_and_ci_materializations(
    subject: str, value: str
) -> None:
    links = chain(subject, value)
    for raw, _ in links:
        cc.validate_products(
            cc.parse(raw), policy=POLICY, policy_ref=POLICY_REF, execution=ci_command()
        )
    for (previous_raw, previous_ref), (raw, _) in zip(links, links[1:]):
        cc.validate_product_transition(previous_raw, previous_ref, cc.parse(raw))
    (reserved_raw, reserved_ref), (observed_raw, observed_ref) = links[:2]
    (accepted_raw, accepted_ref), (restored_raw, restored_ref) = links[2:]
    # A may-live or unknown writer is retained as unknown. It is never accepted
    # directly; after the consumer proves closure it may append a fresh observation
    # pinning the unknown bytes, which then follows the ordinary acceptance path.
    unknown = layer("unknown", reserved_ref, after_ref=None, **{subject: value})
    cc.validate_product_transition(reserved_raw, reserved_ref, unknown)
    cc.validate_product_transition(
        observed_raw, observed_ref, layer("unknown", observed_ref, **{subject: value})
    )
    unknown_raw = cc.encode(unknown)
    unknown_ref = cc.make_ref("products/unknown.json", unknown_raw)
    recovered: list[tuple[bytes, dict[str, object]]] = [(unknown_raw, unknown_ref)]
    fresh = ref("after-reobserved.json")
    for status in ("observed", "accepted", "restored"):
        current = layer(status, recovered[-1][1], after_ref=fresh, **{subject: value})
        cc.validate_products(current, policy=POLICY, execution=ci_command())
        cc.validate_product_transition(*recovered[-1], current)
        raw = cc.encode(current)
        recovered.append((raw, cc.make_ref(f"products/re-{status}.json", raw)))
    for changes in (
        {"command_id": "lint"},
        {"before_ref": ref("other-before.json")},
        {"previous_ref": reserved_ref},
    ):
        current = layer("observed", unknown_ref, after_ref=fresh, **{subject: value})
        with refuses("invalid_product_transition"):
            cc.validate_product_transition(
                unknown_raw, unknown_ref, {**current, **changes}
            )
    illegal = [
        (reserved_raw, reserved_ref, "accepted"),
        (unknown_raw, unknown_ref, "accepted"),
        (unknown_raw, unknown_ref, "restored"),
        (unknown_raw, unknown_ref, "unknown"),
        (observed_raw, observed_ref, "restored"),
        (accepted_raw, accepted_ref, "accepted"),
        (restored_raw, restored_ref, "restored"),
        (restored_raw, restored_ref, "observed"),
    ]
    for previous_raw, previous_ref, status in illegal:
        current = layer(status, previous_ref, **{subject: value})
        with refuses("invalid_product_transition"):
            cc.validate_product_transition(previous_raw, previous_ref, current)


