REASONED = {
    "reason": "measured check output",
    "origin": "operator capture",
    "override": "capture a new policy before init",
}


def refuses(code: str) -> Any:
    return pytest.raises(cc.CheckContractError, match=f"^{code}$")


def rule(surface: str, *prefixes: object) -> dict[str, object]:
    return {"surface": surface, "prefixes": list(prefixes), **REASONED}


def policy_record(*rules: dict[str, object]) -> dict[str, object]:
    return {"format": cc.PATH_POLICY, "rules": list(rules)}


POLICY_RAW = cc.encode(
    policy_record(
        rule("environment_paths", *cc.CACHE_TOKENS, ".venv"),
        rule("product_paths", "htmlcov", "reports/coverage.xml"),
    )
)
POLICY_REF = cc.make_ref("check-path-policy.json", POLICY_RAW)
POLICY = cc.validate_path_policy(cc.parse(POLICY_RAW))


def ref(name: str) -> dict[str, object]:
    return cc.make_ref(name, name.encode())


def execution(**changes: object) -> dict[str, object]:
    value: dict[str, object] = {
        "argv": ["python", "-m", "pytest", "-q", "--cov", "--cov-report=html"],
        "cwd": ".",
        "environment": {
            "inherit_names": ["PATH", "HOME"],
            "set": {"PYTHONHASHSEED": "0"},
        },
        "timeout_seconds": 600,
        "timeout_policy": {
            "reason": "full unit suite measured near seven minutes",
            "origin": "operator profile",
            "override": "edit the captured profile before a new init",
        },
        "expected_exit_code": 0,
        "path_policy_ref": POLICY_REF,
        "expected_products": ["htmlcov"],
    }
    value.update(changes)
    return value


# Original L-Q1 check IDs are unrestricted nonblank text, not graph identifiers.
LQ_ID = "repo:unit suite ✓ — " + "full original check identity " * 4


def ci_command(command_id: str = "unit", **changes: object) -> dict[str, object]:
    return {"id": command_id, **execution(**changes)}


def lq_definition(check_id: str = LQ_ID, **changes: object) -> dict[str, object]:
    shared = execution(**changes)
    # Different key order and the L-Q1-only fields around the same execution.
    return {
        "override": "operator removes the requirement explicitly",
        "origin": "repository acceptance policy",
        "required": True,
        "selection": {"when": "always", "paths": []},
        "requirement_ids": ["task-1:c1"],
        "inputs": ["src"],
        **dict(reversed(list(shared.items()))),
        "purpose": "functional",
        "id": check_id,
    }


def test_stock_policy_is_the_exact_shared_cache_capture() -> None:
    expected = {
        "format": "millrace-check-path-policy/v1",
        "rules": [
            {
                "surface": "environment_paths",
                "prefixes": [
                    "**/__pycache__",
                    "**/.pytest_cache",
                    "**/.mypy_cache",
                    "**/.ruff_cache",
                ],
                "reason": "Python tool caches regenerated by ordinary checks;"
                " opaque environment provenance, never candidate source",
                "origin": "existing CI source-snapshot exclusion"
                " cicd_source.CACHE_DIRS"
                " (__pycache__, .pytest_cache, .mypy_cache, .ruff_cache)",
                "override": "capture a different explicit"
                " millrace-check-path-policy/v1 before init;"
                " a captured policy is never edited in place",
            }
        ],
    }
    raw = cc.stock_path_policy()
    canonical = json.dumps(
        expected, ensure_ascii=False, sort_keys=True, separators=(",", ":")
    ).encode()
    # Every consumer selecting the stock policy pins this one raw identity.
    assert raw == canonical == cc.stock_path_policy()
    assert cc.make_ref("policy.json", raw)["sha256"] == hashlib.sha256(raw).hexdigest()
    stock = cc.validate_path_policy(cc.parse(raw))
    for path in ("__pycache__", "s/__pycache__/m.pyc", ".mypy_cache", "a/.ruff_cache"):
        assert cc.classify(stock, path) == "environment_paths"
    # No legacy LAD exclusion is silently inherited; those need explicit rules.
    for path in (".venv/x", "node_modules/x", "build/x", "dist/x", ".cache/x"):
        assert cc.classify(stock, path) == "source"
    assert cc.classify(stock, "src/x__pycache__") == "source"
    empty = cc.validate_path_policy(policy_record())
    assert cc.classify(empty, "src/__pycache__/m.pyc") == "source"


