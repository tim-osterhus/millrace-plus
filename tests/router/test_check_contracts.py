def command_map(*rows: tuple[str, str, str]) -> dict[str, object]:
    return {
        "format": cc.COMMAND_MAP,
        "entries": [
            {"lq_check_id": check, "ci_command_id": command, "execution_sha256": digest}
            for check, command, digest in rows
        ],
    }


def test_command_map_resolves_every_lq_check_to_one_identical_execution() -> None:
    lint: dict[str, object] = {
        "argv": ["ruff", "check", "src"],
        "expected_products": [],
        "timeout_seconds": 60,
    }
    lq = {
        LQ_ID: lq_definition(),
        "lint": lq_definition("lint", **lint),
        "lint-required-alias": lq_definition("lint-required-alias", **lint),
    }
    ci = {"unit": ci_command(), "lint": ci_command("lint", **lint)}
    unit = cc.execution_sha256(execution())
    linted = cc.execution_sha256(execution(**lint))
    rows = [
        (LQ_ID, "unit", unit),
        ("lint", "lint", linted),
        ("lint-required-alias", "lint", linted),
    ]
    # Two L-Q1 identities may share one exact CI execution without a second dispatch.
    assert cc.verify_command_map(command_map(*rows), lq, ci) == {
        LQ_ID: "unit",
        "lint": "lint",
        "lint-required-alias": "lint",
    }
    slower = {**ci, "unit": ci_command(timeout_seconds=900)}
    unproducing = {**lq, LQ_ID: lq_definition(expected_products=[])}
    refusals = [
        (command_map(*rows[1:]), lq, ci, "command_map_incomplete"),
        (command_map(*rows, ("ghost", "unit", unit)), lq, ci, "command_map_incomplete"),
        (
            command_map((LQ_ID, "missing", unit), *rows[1:]),
            lq,
            ci,
            "command_map_unknown_command",
        ),
        (command_map(*rows), lq, slower, "command_map_execution_mismatch"),
        (command_map(*rows), unproducing, ci, "command_map_execution_mismatch"),
        (
            command_map((LQ_ID, "unit", linted), *rows[1:]),
            lq,
            ci,
            "command_map_execution_mismatch",
        ),
        (command_map(*rows, rows[0]), lq, ci, "invalid_command_map"),
        (
            command_map((LQ_ID, "unit", unit), ("lint", "unit", linted)),
            lq,
            ci,
            "invalid_command_map",
        ),
        (
            {**command_map(*rows), "format": "millrace-check-command-map/v2"},
            lq,
            ci,
            "invalid_command_map",
        ),
        (
            command_map((LQ_ID, "unit", unit.upper()), *rows[1:]),
            lq,
            ci,
            "invalid_command_map",
        ),
    ]
    for record, checks, commands, code in refusals:
        with refuses(code):
            cc.verify_command_map(record, checks, commands)


def test_module_stays_pure_and_core_free() -> None:
    tree = ast.parse(Path(cc.__file__).read_text())
    nodes = list(ast.walk(tree))
    absolute = {
        alias.name.split(".")[0]
        for node in nodes
        if isinstance(node, ast.Import)
        for alias in node.names
    } | {
        (node.module or "").split(".")[0]
        for node in nodes
        if isinstance(node, ast.ImportFrom) and node.level == 0
    }
    forbidden = {"os", "subprocess", "shutil", "socket", "signal", "selectors"}
    forbidden |= {"sqlite3", "importlib", "sys", "tempfile", "threading", "time"}
    assert absolute.isdisjoint(forbidden | {"fcntl", "millrace"})
    # Only the canonical/strict JSON helpers are shared with local intake.
    relative = {
        node.module for node in nodes if isinstance(node, ast.ImportFrom) and node.level
    }
    assert relative == {"local_intake"}
    pathlib = [
        alias.name
        for node in nodes
        if isinstance(node, ast.ImportFrom) and node.module == "pathlib"
        for alias in node.names
    ]
    assert pathlib == ["PurePosixPath"]
    called = {
        node.func.id
        for node in nodes
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
    }
    assert called.isdisjoint({"open", "exec", "eval", "__import__", "input"})
