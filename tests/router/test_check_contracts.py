def test_execution_digest_is_shared_by_ci_command_and_lq_check_definition() -> None:
    ci = cc.execution_of(ci_command(), policy=POLICY, policy_ref=POLICY_REF)
    lq = cc.execution_of(lq_definition(), policy=POLICY, policy_ref=POLICY_REF)
    assert ci == lq == execution()
    digest = cc.execution_sha256(ci)
    reordered = dict(reversed(list(execution().items())))
    assert digest == cc.execution_sha256(lq) == cc.execution_sha256(reordered)
    # Every execution field is identity; there is no numeric or order normalization.
    policy = {**REASONED, "reason": "other"}
    seed, reseeded = {"PYTHONHASHSEED": "0"}, {"PYTHONHASHSEED": "1"}
    mutants = [
        execution(argv=["python", "-m", "pytest", "-q", "--cov", "--cov-report=xml"]),
        execution(cwd="src"),
        execution(environment={"inherit_names": ["PATH"], "set": seed}),
        execution(environment={"inherit_names": ["HOME", "PATH"], "set": seed}),
        execution(environment={"inherit_names": ["PATH", "HOME"], "set": reseeded}),
        execution(timeout_seconds=601),
        execution(timeout_seconds=600.0),
        execution(timeout_policy=policy),
        execution(expected_exit_code=5),
        execution(path_policy_ref=cc.make_ref("check-path-policy.json", b"{}")),
        execution(expected_products=["htmlcov", "reports/coverage.xml"]),
        execution(expected_products=["reports/coverage.xml", "htmlcov"]),
    ]
    digests = {cc.execution_sha256(item) for item in mutants}
    assert len(digests) == len(mutants) and digest not in digests
    with refuses("invalid_execution"):
        cc.execution_sha256(ci_command())  # the command ID is not execution identity


