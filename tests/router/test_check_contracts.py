def test_cache_selectors_never_classify_git_or_owner_authority() -> None:
    stock = cc.validate_path_policy(cc.parse(cc.stock_path_policy()))
    token = cc.validate_path_policy(
        policy_record(rule("product_paths", "**/__pycache__", "**/.pytest_cache"))
    )
    writer = execution(expected_products=["**/__pycache__", "**/.pytest_cache"])
    for path in STRUCTURAL_PATHS:
        assert cc.classify(stock, path) == cc.classify(token, path) == "source", path
        assert not cc.product_write_allowed(token, writer, path), path
    # Ordinary cache behaviour is unchanged outside Git/owner structure.
    assert cc.classify(stock, "src/__pycache__/m.pyc") == "environment_paths"
    assert cc.product_write_allowed(token, writer, "src/__pycache__/m.pyc")
    # Authority stays checkable as unmasked source; it is never an opaque entry.
    cc.require_source(stock, [lad_service.OWNER, ".git/config"])
    git_cache = cc.environment_entry(".git/__pycache__", lstat(stat.S_IFDIR))
    with refuses("environment_not_opaque"):
        cc.validate_environment(environment(git_cache), policy=stock)
    record = layer("observed", ref("r.json"), input_id="i", owned_paths=["src/.git/x"])
    with refuses("undeclared_output"):
        cc.validate_products(record, policy=token, execution=writer)


