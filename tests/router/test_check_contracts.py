def test_inherited_timeout_matches_core_settings_resolution(
    tmp_path: Path, single_flow: tuple[Path, Path, Path]
) -> None:
    from plus_support import new_id

    from millrace_plus.router import control

    workflow, project, _ = single_flow
    original = json.loads(workflow.read_text())
    original["planes"]["main"]["nodes"]["draft"]["invoke"].pop("timeout_seconds")
    cases: tuple[tuple[dict[str, int], dict[str, int]], ...] = (
        ({}, {}),
        ({"timeout_seconds": 40}, {}),
        ({"timeout_seconds": 40}, {"timeout_seconds": 25}),
    )
    for index, (workflow_defaults, plane_defaults) in enumerate(cases):
        graph = json.loads(json.dumps(original))
        graph["defaults"] = workflow_defaults
        graph["planes"]["main"]["defaults"] = plane_defaults
        workflow.write_text(json.dumps(graph))
        home = tmp_path / f"home-{index}"
        created = control.create_instance(
            workflow,
            project,
            state_home=home,
            request_id=new_id(),
            expected_state_version=0,
        )
        assert created["status"] == "applied", created
        common = control.validate_revision(created["instance_id"], state_home=home)[
            "resolved_nodes"
        ]["main"]["draft"]["common"]
        ours = cc.resolve_timeout(
            None,
            None,
            plane=plane_defaults.get("timeout_seconds"),
            workflow=workflow_defaults.get("timeout_seconds"),
        )
        assert common["effective"]["timeout_seconds"] == ours["timeout_seconds"]
        assert common["provenance"]["timeout_seconds"]["source"] == ours["source"]
        assert [warning["code"] for warning in common["warnings"]] == (
            [ours["warning"]] if ours["warning"] else []
        )


